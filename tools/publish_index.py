"""Export complete RSI packages from a committed revision into OpenRSI-Index."""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPOSITORY = 'OpenRSI-Foundation/Agent4Sci-RSI-Harbor'
INDEX_MARKER = '<!-- Generated by Agent4Sci-RSI-Harbor/tools/publish_index.py. -->'


def git(*args: str) -> bytes:
    return subprocess.check_output(['git', '-C', str(ROOT), *args])


def fingerprint(content: bytes, mode: str, source_path=None) -> dict:
    result = {'sha256': hashlib.sha256(content).hexdigest(), 'bytes': len(content), 'mode': mode}
    if source_path is not None:
        result['source_path'] = source_path
    return result


def task_readme(spec: dict, commit: str) -> bytes:
    task, metric = spec['id'], spec['metric']
    text = f'''# {spec['title']}

RSI task: `rsi/{task}`. Domain: **{spec['domain']}**. Track: **{spec['track']}**.
This is a complete OpenRSI-Index task, in Harbor 1.4 format, executed by this
repository's [RSI-Harness](../../RSI-Harness/).

## Research contract

Improve `{metric['name']}` ({metric['unit']}, **{metric['direction']}**) on
`{spec['project']}/{spec['data_task']}`. Develop models, training methods,
features, preprocessing and inference inside `/workspace/runs` using train/val
feedback. The pinned reference implementation, splits and scientific metric
remain fixed. See [instruction.md](instruction.md) for the full action space.

{spec['protocol']}

| Field | Contract |
|---|---|
| Upstream paper baseline | {spec['baseline']['paper'] if spec['baseline']['paper'] is not None else 'Not reported'} |
| Upstream reproduction baseline | {spec['baseline']['reproduction']} (reported upstream; not remeasured here) |
| Required seed/fold components | {', '.join(spec['components'])} |
| Component aggregation | {spec['aggregation']} |
| Work budget | 12 hours, 8 H200 GPUs |
| Judge allocation | 8 GPUs; may time-share the Work pool |
| CPU / RAM / planned disk | 32 cores / 512 GiB / 1 TiB |
| Submission | Selected checkpoints, loading code, SUMMARY.md and METHODOLOGY.md in `/workspace/runs` |
| Primary reward | `reward`, maximize; baseline maps to 0.5 |
| Invalid/incomplete evaluation | Unscored; no synthetic reward |
| Final held-out submissions | 1, enforced with `--max-submissions 1` |

The agent iterates on train/val throughout Work and submits once for final
held-out evaluation plus integrity audit. Repeated feedback from the held-out
test set would change the upstream protocol; this publication does not make that
change. Each split subtask has an independent allocation, which changes the total
compute relative to an upstream shared-project run.

## Run with OpenRSI-Index

Install from the repository root with `uv tool install ./RSI-Harness`, following
the [Index Quick Start](../../assets/docs/quick-start.md). Set `RSI_MODEL`,
`RSI_REASONING_EFFORT`, and `RSI_GPU_POOL` for the research agent. Supply
`ANTHROPIC_API_KEY` and `AGENT4SCI_JUDGE_MODEL` for the separate evaluator and
auditor; those values reach only the verifier. Then, from the Index root:

```bash
sudo -E "$(command -v rsi-harness)" run "$PWD/rsi-tasks/{task}" \\
  --agent codex --agent-auth local \\
  --model "$RSI_MODEL" --reasoning-effort "$RSI_REASONING_EFFORT" \\
  --gpus "$RSI_GPU_POOL" \\
  --primary-reward reward --score-direction maximize \\
  --max-submissions 1 --verbose
```

Use `rsi-submit` once when final. The supported entry point is `rsi-harness`,
not `harbor run`. This adapter currently requires a root-capable Linux x86-64
Docker Judge; it has not been ported to non-root cluster Judges.

## Work and Judge boundaries

The source image and dataset revision are fixed in [tests/spec.json](tests/spec.json).
Train/val are prepared during image construction. Judge starts from the clean
image, reads `/workspace` as a read-only snapshot, and stages test data separately.
Loading/inference code must accept explicit data and output paths; any custom
venv must be under `/workspace/runs`. The evaluator writes retained evidence to
`/logs/verifier/candidate_outputs`. The host-captured `/logs/agent` trajectory is
checked for complete sizes and SHA-256 digests and is the primary audit evidence.

Reward is `0.5 + atan(d * (metric - baseline) / abs(baseline)) / pi`, with
`d=1` for maximize and `d=-1` for minimize. It requires independently reported
complete metrics and a CLEAN audit. Model-based evaluation/audit and public
dataset availability retain the limitations described in the
[collection guide](../AGENT4SCI.md); this is not an adversarial-code sandbox.

## Validation and provenance

All 26 source packages passed RSI-Harness/Harbor model compilation, CPU adapter
tests and synthetic Linux read-only/UID contract tests. These are packaging
checks. Scientific image builds, GPU baselines, real evaluator/auditor calls and
the live RSI Work/snapshot/Judge lifecycle remain unvalidated. No validated
oracle solution is supplied. Use the pinned reproduction code to establish a
matched baseline on the execution host before making scientific claims.

Source package: [{REPOSITORY} at {commit[:12]}](https://github.com/{REPOSITORY}/tree/{commit}/tasks/{task}).
[publication.json](publication.json) records the immutable source and original
and published file hashes. Runtime/task files are copied completely; this README
uses the Index's local execution paths. [LICENSE](LICENSE) and [NOTICE](NOTICE)
preserve the Apache-2.0 adapter attribution; underlying assets retain their terms.
'''
    return text.encode()



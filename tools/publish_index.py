def payload(revision: str) -> dict[str, tuple[bytes, str]]:
    commit = git('rev-parse', '--verify', '--end-of-options', revision + '^{commit}').decode().strip()
    catalog = json.loads(git('show', f'{commit}:catalog.json'))
    result = {'rsi-tasks/AGENT4SCI.md': (collection_readme(catalog, commit), '100644')}
    for spec in catalog['tasks']:
        slug = spec['id']
        if not re.fullmatch(r'agent4sci-[a-z0-9]+(?:-[a-z0-9]+)*', slug):
            raise ValueError(f'Invalid task ID: {slug}')
        prefix, original, package = f'tasks/{slug}/', {}, {}
        records = git('ls-tree', '-r', '-z', commit, '--', prefix).split(b'\0')
        for record in filter(None, records):
            metadata, path = record.decode().split('\t', 1)
            mode, kind, blob = metadata.split()
            if kind != 'blob' or mode not in ('100644', '100755'):
                raise ValueError(f'Only regular tracked source files may be published: {path}')
            contents = git('cat-file', 'blob', blob)
            name = path.removeprefix(prefix)
            package[name] = (contents, mode)
            original[name] = fingerprint(contents, mode, path) | {'git_blob': blob}
        if not {'task.toml', 'instruction.md', 'tests/test.sh', 'environment/Dockerfile'} <= package.keys():
            raise ValueError(f'Incomplete source package: {slug}')
        package['README.md'] = (task_readme(spec, commit), '100644')
        for name in ('LICENSE', 'NOTICE'):
            contents = git('show', f'{commit}:{name}')
            package[name] = (contents, '100644')
            original[name] = fingerprint(contents, '100644', name)
        public_path = f'rsi-tasks/{slug}'
        receipt = {
            'source_repository': REPOSITORY, 'source_commit': commit,
            'original_task_slug': slug, 'public_path': public_path, 'domain': spec['domain'],
            'upstream_revision': spec['upstream_revision'],
            'publication_changes': ['Use OpenRSI-Index local run/documentation paths in README.md.',
                                    'Include source LICENSE and NOTICE in the standalone package.',
                                    'Record immutable provenance and file hashes; scientific protocol is unchanged.'],
            'original_files': original,
            'published_files': {name: fingerprint(contents, mode)
                                for name, (contents, mode) in package.items()},
        }
        package['publication.json'] = ((json.dumps(receipt, indent=2) + '\n').encode(), '100644')
        result.update({f'{public_path}/{name}': item for name, item in package.items()})
    return result


def publish(index: Path, files: dict, *, check: bool = False) -> None:
    tasks = index / 'rsi-tasks'
    if tasks.is_symlink():
        raise ValueError('Refusing a symlinked rsi-tasks directory')
    for root in {Path(name).parts[1] for name in files if name != 'rsi-tasks/AGENT4SCI.md'}:
        directory = tasks / root
        if directory.exists() or directory.is_symlink():
            if directory.is_symlink() or any(p.is_symlink() for p in directory.rglob('*')):
                raise ValueError(f'Refusing publication through symlinks: {root}')
            receipt = directory / 'publication.json'
            if not receipt.is_file() or json.loads(receipt.read_text()).get('source_repository') != REPOSITORY:
                raise ValueError(f'Refusing to overwrite an unrelated Index task: {root}')
            extras = {p.relative_to(index).as_posix() for p in directory.rglob('*') if p.is_file()} - files.keys()
            if extras:
                raise ValueError(f'Unexpected files in {root}; reconcile them explicitly')
    guide = tasks / 'AGENT4SCI.md'
    if guide.exists() and not guide.read_text().startswith(INDEX_MARKER):
        raise ValueError('Refusing to overwrite an unrelated collection guide')
    stale = []
    for name, (contents, mode) in files.items():
        path = index / name
        if path.is_symlink():
            raise ValueError(f'Refusing symlink: {name}')
        if check:
            executable = mode == '100755'
            if not path.is_file() or path.read_bytes() != contents or bool(path.stat().st_mode & 0o111) != executable:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(contents)
            path.chmod(0o755 if mode == '100755' else 0o644)
    if stale:
        raise ValueError('Publication differs from its pinned source:\n' + '\n'.join(stale))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--index', type=Path, required=True)
    parser.add_argument('--revision', required=True, help='committed source revision; no uncommitted files are read')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = payload(args.revision)
    publish(args.index.resolve(), files, check=args.check)
    print(f'{"Checked" if args.check else "Exported"} 26 complete RSI tasks and the OpenRSI-Index collection guide')


if __name__ == '__main__':
    main()
